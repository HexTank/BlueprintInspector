const TCHAR* const FixtureObjectPath = TEXT("/BlueprintInspector/Tests/OpcodeShowcase/BP_OpcodeDemo_All.BP_OpcodeDemo_All");

FString ArchiveDir()
{
    const TSharedPtr<IPlugin> Plugin = IPluginManager::Get().FindPlugin(TEXT("BlueprintInspector"));
    if (!Plugin.IsValid())
    {
        return FString();
    }
    return FPaths::Combine(Plugin->GetBaseDir(), TEXT("Content/Tests/OpcodeShowcase/Graphs"));
}

struct FPinSpec
{
    FString NodeName;
    FString PinName;
    FString DefaultValue;
    FString DefaultText;
    FString DefaultObject;
    bool bHasDefaultValue = false;
    bool bHasDefaultText = false;
};

// Finds a property by name without matching the tail of another property (AutogeneratedDefaultValue
// contains DefaultValue). Values are comma-separated on one line; quoted values may contain commas.
int32 FindProperty(const FString& Line, const TCHAR* const Key)
{
    int32 Search = 0;
    while (true)
    {
        const int32 Position = Line.Find(Key, ESearchCase::CaseSensitive, ESearchDir::FromStart, Search);
        if (Position == INDEX_NONE)
        {
            return INDEX_NONE;
        }
        if (Position == 0 || (!FChar::IsAlnum(Line[Position - 1]) && Line[Position - 1] != TEXT('_')))
        {
            return Position;
        }
        Search = Position + 1;
    }
}

bool ExtractValue(const FString& Line, const TCHAR* const Key, FString& OutValue)
{
    const int32 Position = FindProperty(Line, Key);
    if (Position == INDEX_NONE)
    {
        return false;
    }

    int32 Start = Position + FCString::Strlen(Key);
    while (Start < Line.Len() && FChar::IsWhitespace(Line[Start]))
    {
        ++Start;
    }
    if (Start >= Line.Len())
    {
        return false;
    }

    if (Line[Start] != TEXT('"'))
    {
        // An unquoted value can still contain commas inside a struct/container literal, e.g.
        // (X=1,Y=2) or (Greeting="a,b"). Only a top-level comma outside quotes ends the value.
        bool bInQuotes = false;
        bool bEscaped = false;
        int32 Depth = 0;
        int32 End = Start;
        for (; End < Line.Len(); ++End)
        {
            const TCHAR Character = Line[End];
            if (bEscaped)
            {
                bEscaped = false;
            }
            else if (bInQuotes && Character == TEXT('\\'))
            {
                bEscaped = true;
            }
            else if (Character == TEXT('"'))
            {
                bInQuotes = !bInQuotes;
            }
            else if (!bInQuotes)
            {
                if (Character == TEXT('(') || Character == TEXT('[') || Character == TEXT('{'))
                {
                    ++Depth;
                }
                else if (Character == TEXT(')') || Character == TEXT(']') || Character == TEXT('}'))
                {
                    Depth = FMath::Max(0, Depth - 1);
                }
                else if (Character == TEXT(',') && Depth == 0)
                {
                    break;
                }
            }
        }
        if (bInQuotes || Depth != 0)
        {
            UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: unterminated value for %s in an archive line."), Key);
            return false;
        }
        OutValue = Line.Mid(Start, End - Start);
        OutValue.TrimStartAndEndInline();
        return true;
    }

    ++Start;
    FString Value;
    bool bEscaped = false;
    for (int32 Index = Start; Index < Line.Len(); ++Index)
    {
        const TCHAR Character = Line[Index];
        if (bEscaped)
        {
            switch (Character)
            {
            case 'n':
                Value.AppendChar(static_cast<TCHAR>(0x0A));
                break;
            case 'r':
                Value.AppendChar(static_cast<TCHAR>(0x0D));
                break;
            case 't':
                Value.AppendChar(static_cast<TCHAR>(0x09));
                break;
            case 0x5C:
                Value.AppendChar(static_cast<TCHAR>(0x5C));
                break;
            case '"':
                Value.AppendChar(TEXT('"'));
                break;
            default:
                Value.AppendChar(static_cast<TCHAR>(0x5C));
                Value.AppendChar(Character);
                break;
            }
            bEscaped = false;
        }
        else if (Character == TEXT('\\'))
        {
            bEscaped = true;
        }
        else if (Character == TEXT('"'))
        {
            OutValue = Value;
            return true;
        }
        else
        {
            Value.AppendChar(Character);
        }
    }
    UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: unterminated quoted value for %s in an archive line."), Key);
    return false;
}

void ParseGraphText(const FString& Text, TArray<FPinSpec>& OutPins)
{
    TArray<FString> Lines;
    Text.ParseIntoArrayLines(Lines, false);

    FString CurrentNode;
    for (const FString& Line : Lines)
    {
        FString Trimmed = Line;
        Trimmed.TrimStartInline();

        if (Trimmed.StartsWith(TEXT("Begin Object ")))
        {
            FString Name;
            if (ExtractValue(Trimmed, TEXT("Name="), Name))
            {
                CurrentNode = Name;
            }
            continue;
        }

        if (Trimmed.StartsWith(TEXT("End Object")))
        {
            CurrentNode.Reset();
            continue;
        }

        if (CurrentNode.IsEmpty() || !Line.Contains(TEXT("CustomProperties Pin (")))
        {
            continue;
        }

        FPinSpec Spec;
        Spec.NodeName = CurrentNode;
        if (!ExtractValue(Line, TEXT("PinName="), Spec.PinName) || Spec.PinName.IsEmpty())
        {
            continue;
        }
        Spec.bHasDefaultValue = ExtractValue(Line, TEXT("DefaultValue="), Spec.DefaultValue);
        Spec.bHasDefaultText = ExtractValue(Line, TEXT("DefaultTextValue="), Spec.DefaultText);
        ExtractValue(Line, TEXT("DefaultObject="), Spec.DefaultObject);
        OutPins.Add(MoveTemp(Spec));
    }
}

template <typename TGraphArray>
UEdGraph* FindGraphIn(const TGraphArray& Graphs, const FString& GraphName)
{
    for (UEdGraph* const Graph : Graphs)
    {
        if (Graph != nullptr && Graph->GetName() == GraphName)
        {
            return Graph;
        }
    }
    return nullptr;
}

UEdGraph* FindGraph(UBlueprint* const Fixture, const FString& GraphName)
{
    if (Fixture == nullptr)
    {
        return nullptr;
    }

    // The archive holds every authored graph, not only function graphs: EventGraph is an ubergraph and
    // macro/delegate-signature graphs appear too. Searching FunctionGraphs alone silently left those
    // unrepaired.
    if (UEdGraph* const Found = FindGraphIn(Fixture->FunctionGraphs, GraphName))
    {
        return Found;
    }
    if (UEdGraph* const Found = FindGraphIn(Fixture->UbergraphPages, GraphName))
    {
        return Found;
    }
    if (UEdGraph* const Found = FindGraphIn(Fixture->MacroGraphs, GraphName))
    {
        return Found;
    }
    if (UEdGraph* const Found = FindGraphIn(Fixture->DelegateSignatureGraphs, GraphName))
    {
        return Found;
    }
    return nullptr;
}

UEdGraphPin* FindPin(UEdGraph* const Graph, const FPinSpec& Spec)
{
    for (UEdGraphNode* const Node : Graph->Nodes)
    {
        if (Node == nullptr || Node->GetName() != Spec.NodeName)
        {
            continue;
        }
        for (UEdGraphPin* const Pin : Node->Pins)
        {
            if (Pin != nullptr && Pin->PinName.ToString() == Spec.PinName)
            {
                return Pin;
            }
        }
    }
    return nullptr;
}

bool HasCorrectDefaults(UBlueprint* const Fixture, const FString& ArchiveDirectory, const TArray<FString>& Files)
{
    for (const FString& File : Files)
    {
        FString Text;
        if (!FFileHelper::LoadFileToString(Text, *FPaths::Combine(ArchiveDirectory, File)))
        {
            return false;
        }

        UEdGraph* const Graph = FindGraph(Fixture, FPaths::GetBaseFilename(File));
        if (Graph == nullptr)
        {
            return false;
        }

        TArray<FPinSpec> Specs;
        ParseGraphText(Text, Specs);
        for (const FPinSpec& Spec : Specs)
        {
            UEdGraphPin* const Pin = FindPin(Graph, Spec);
            if (Pin == nullptr)
            {
                return false;
            }

            if (Pin->PinType.PinCategory == UEdGraphSchema_K2::PC_Text)
            {
                if (Spec.bHasDefaultText || Spec.bHasDefaultValue)
                {
                    const FString& Expected = Spec.bHasDefaultText ? Spec.DefaultText : Spec.DefaultValue;
                    if (Pin->DefaultValue != Expected || !Pin->DefaultTextValue.ToString().Equals(Expected, ESearchCase::CaseSensitive))
                    {
                        return false;
                    }
                }
            }
            else if (Spec.bHasDefaultValue)
            {
                FString Expected = Spec.DefaultValue;
                if (Pin->PinType.PinCategory == UEdGraphSchema_K2::PC_Struct && Expected.StartsWith(TEXT("(")))
                {
                    if (UScriptStruct* const Struct = Cast<UScriptStruct>(Pin->PinType.PinSubCategoryObject.Get()))
                    {
                        Expected = BlueprintStructDefaults::RewriteStructDefault(Struct, Expected);
                    }
                }
                if (Pin->DefaultValue != Expected)
                {
                    return false;
                }
            }

            const bool bHardObjectPin = Pin->PinType.PinCategory == UEdGraphSchema_K2::PC_Object || Pin->PinType.PinCategory == UEdGraphSchema_K2::PC_Class;
            if (bHardObjectPin && Spec.DefaultObject.Equals(TEXT("None"), ESearchCase::IgnoreCase))
            {
                if (Pin->DefaultObject != nullptr)
                {
                    return false;
                }
            }
            else if (!Spec.DefaultObject.IsEmpty() && !Spec.DefaultObject.Equals(TEXT("None"), ESearchCase::IgnoreCase))
            {
                UObject* const ExpectedObject = LoadObject<UObject>(nullptr, *Spec.DefaultObject);
                if (ExpectedObject == nullptr || Pin->DefaultObject != ExpectedObject)
                {
                    return false;
                }
            }
        }
    }
    return true;
}

void ApplyPinSpecs(UEdGraph* const Graph, const TArray<FPinSpec>& Specs)
{
    for (const FPinSpec& Spec : Specs)
    {
        UEdGraphPin* const Found = FindPin(Graph, Spec);
        if (Found == nullptr)
        {
            UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: archive pin %s on node %s matches no live pin in graph %s."), *Spec.PinName, *Spec.NodeName, *Graph->GetName());
            continue;
        }

        if (Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Text)
        {
            if (Spec.bHasDefaultText || Spec.bHasDefaultValue)
            {
                const FString& Text = Spec.bHasDefaultText ? Spec.DefaultText : Spec.DefaultValue;
                // Keep the string members in sync with the text value: the K2 schema mirrors text-pin
                // state in DefaultValue, and a following compile can otherwise undo the text default.
                Found->DefaultTextValue = FText::FromString(Text);
                Found->DefaultValue = Text;
                Found->AutogeneratedDefaultValue = Text;
            }
        }
        else if (Spec.bHasDefaultValue)
        {
            const bool bStructLiteral = Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Struct && Spec.DefaultValue.StartsWith(TEXT("("));
            if (bStructLiteral)
            {
                if (UScriptStruct* const Struct = Cast<UScriptStruct>(Found->PinType.PinSubCategoryObject.Get()))
                {
                    Found->DefaultValue = BlueprintStructDefaults::RewriteStructDefault(Struct, Spec.DefaultValue);
                }
                else
                {
                    // A struct-category pin without a struct object cannot be rewritten; keep the text
                    // rather than dereferencing a null struct in the helper.
                    Found->DefaultValue = Spec.DefaultValue;
                }
            }
            else
            {
                Found->DefaultValue = Spec.DefaultValue;
            }
            Found->AutogeneratedDefaultValue = Found->DefaultValue;
        }

        const bool bObjectPin = Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Object || Found->PinType.PinCategory == UEdGraphSchema_K2::PC_SoftObject || Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Class || Found->PinType.PinCategory == UEdGraphSchema_K2::PC_SoftClass;
        const bool bHardObjectPin = Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Object || Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Class;
        if (bHardObjectPin && Spec.DefaultObject.Equals(TEXT("None"), ESearchCase::IgnoreCase))
        {
            Found->DefaultObject = nullptr;
            Found->DefaultValue = TEXT("None");
            Found->AutogeneratedDefaultValue = TEXT("None");
        }
        else if (!Spec.DefaultObject.IsEmpty() && !Spec.DefaultObject.Equals(TEXT("None"), ESearchCase::IgnoreCase))
        {
            UClass* const ExpectedClass = bObjectPin ? Cast<UClass>(Found->PinType.PinSubCategoryObject.Get()) : nullptr;
            const bool bClassPin = Found->PinType.PinCategory == UEdGraphSchema_K2::PC_Class || Found->PinType.PinCategory == UEdGraphSchema_K2::PC_SoftClass;
            UObject* const DefaultObject = LoadObject<UObject>(nullptr, *Spec.DefaultObject);
            bool bMatches = DefaultObject != nullptr;
            if (bMatches && ExpectedClass != nullptr)
            {
                if (bClassPin)
                {
                    const UClass* const DefaultClass = Cast<UClass>(DefaultObject);
                    bMatches = DefaultClass != nullptr && DefaultClass->IsChildOf(ExpectedClass);
                }
                else
                {
                    bMatches = DefaultObject->IsA(ExpectedClass);
                }
            }
            if (!bMatches)
            {
                UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: default object %s for pin %s on %s is missing or not a %s."), *Spec.DefaultObject, *Spec.PinName, *Spec.NodeName, ExpectedClass != nullptr ? *ExpectedClass->GetName() : TEXT("matching object"));
            }
            else
            {
                Found->DefaultObject = DefaultObject;
                Found->DefaultValue = Spec.bHasDefaultValue ? Spec.DefaultValue : DefaultObject->GetPathName();
                Found->AutogeneratedDefaultValue = Found->DefaultValue;
            }
        }
    }
}
