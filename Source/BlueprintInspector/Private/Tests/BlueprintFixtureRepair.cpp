bool RepairLoadedFixture(UBlueprint* Fixture)
{
    if (Fixture == nullptr)
    {
        return false;
    }

    const FString ArchiveDirectory = ArchiveDir();
    if (ArchiveDirectory.IsEmpty())
    {
        UE_LOG(LogBlueprintInspector, Error, TEXT("Fixture repair: the BlueprintInspector plugin was not found; the repair is a no-op."));
        return false;
    }

    TArray<FString> Files;
    IFileManager::Get().FindFiles(Files, *FPaths::Combine(ArchiveDirectory, TEXT("*.txt")), true, false);
    if (Files.Num() == 0)
    {
        UE_LOG(LogBlueprintInspector, Error, TEXT("Fixture repair: no graph archive under %s."), *ArchiveDirectory);
        return false;
    }

    if (HasCorrectDefaults(Fixture, ArchiveDirectory, Files))
    {
        return true;
    }

    const auto ApplyArchive = [&Fixture, &Files, &ArchiveDirectory]() {
        for (const FString& File : Files)
        {
            FString Text;
            if (!FFileHelper::LoadFileToString(Text, *FPaths::Combine(ArchiveDirectory, File)))
            {
                UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: could not read the archive file %s."), *File);
                continue;
            }

            const FString GraphName = FPaths::GetBaseFilename(File);
            UEdGraph* const Graph = FindGraph(Fixture, GraphName);
            if (Graph == nullptr)
            {
                UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: archive graph %s matches no graph on %s."), *GraphName, *Fixture->GetName());
                continue;
            }

            TArray<FPinSpec> Specs;
            ParseGraphText(Text, Specs);
            ApplyPinSpecs(Graph, Specs);
        }
    };

    ApplyArchive();
    FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Fixture);
    FKismetEditorUtilities::CompileBlueprint(Fixture);
    ApplyArchive();

    if (Fixture->Status == BS_Error)
    {
        UE_LOG(LogBlueprintInspector, Error, TEXT("Fixture repair: %s failed to compile after the archive defaults were applied."), *Fixture->GetName());
        return false;
    }
    if (!HasCorrectDefaults(Fixture, ArchiveDirectory, Files))
    {
        UE_LOG(LogBlueprintInspector, Error, TEXT("Fixture repair: %s still has reset pin defaults after recompiling; the archive did not restore them."), *Fixture->GetName());
        return false;
    }
    return true;
}

UBlueprint* LoadRepairedFixture()
{
    UBlueprint* const Fixture = LoadObject<UBlueprint>(nullptr, FixtureObjectPath);
    if (Fixture == nullptr)
    {
        UE_LOG(LogBlueprintInspector, Warning, TEXT("Fixture repair: %s could not be loaded; the repair is a no-op."), FixtureObjectPath);
        return nullptr;
    }

    RepairLoadedFixture(Fixture);
    return Fixture;
}
